const FEE = /^Instant cash-out fee is \$(\d+\.\d{2})\.$/;

function languageOf(req) {
  const header = String((req && req.headers && req.headers["accept-language"]) || "en").toLowerCase();
  if (header.startsWith("zh")) return "zh";
  if (header.startsWith("es")) return "es";
  return "en";
}

function translate(language, value) {
  if (typeof value !== "string" || language === "en") return value;
  const row = EXACT[value];
  if (row) return language === "zh" ? row[1] : row[0];
  const fee = value.match(FEE);
  if (fee) {
    return language === "zh" ? `即时提现手续费为 $${fee[1]}。` : `La comisión del cobro instantáneo es $${fee[1]}.`;
  }
  return value;
}

const TEXT_KEYS = new Set(["error", "message", "note", "reason", "title", "body", "label", "area"]);

function walk(value, language) {
  if (typeof value === "string") return translate(language, value);
  if (Array.isArray(value)) return value.map((item) => walk(item, language));
  if (!value || typeof value !== "object") return value;
  const copy = {};
  for (const [key, item] of Object.entries(value)) {
    if (typeof item === "string" && TEXT_KEYS.has(key)) copy[key] = translate(language, item);
    else if (item && typeof item === "object") copy[key] = walk(item, language);
    else copy[key] = item;
  }
  return copy;
}

function localize(req, body) {
  const language = languageOf(req);
  if (language === "en" || !body || typeof body !== "object") return body;
  return walk(body, language);
}

module.exports = { localize, translate, languageOf };
